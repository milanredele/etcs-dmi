class Message:
    def __init__(self, spec, variables):
        try:
            self.nid = int(spec["nid"])
            self.name = str(spec["name"])
            self.clause = str(spec["clause"])
            self.direction = str(spec["direction"])
            fields = spec["fields"]
            rules = spec.get("packets", [])
        except KeyError as e:
            fail("message: missing %s" % e)
        if self.direction not in DIRECTIONS:
            fail("message %d: direction %s" % (self.nid, self.direction))
        if not 0 <= self.nid <= 255:
            fail("message %d: NID_MESSAGE not in 0 .. 255" % self.nid)
        for key in spec:
            if key not in ("nid", "name", "clause", "direction", "sent_by",
                           "fields", "packets"):
                fail("message %d: unknown key %s" % (self.nid, key))
        self.sent_by = [str(x).lower() for x in spec.get("sent_by", [])]
        for x in self.sent_by:
            if x not in SENDERS:
                fail("message %d: sent_by %s" % (self.nid, x))
        self.dir_ada = DIRECTIONS[self.direction][0]
        self.kind = "%s_M%d" % (DIRECTIONS[self.direction][2], self.nid)
        self.fields = []
        names = set()
        for f in fields:
            if set(f) - {"var", "as"} or "var" not in f:
                fail("message %d: only var fields are supported, not %r"
                     % (self.nid, f))
            if f["var"] not in variables:
                fail("message %d: variable %s is not described"
                     % (self.nid, f["var"]))
            comp = f.get("as", f["var"])
            if comp in names:
                fail("message %d: %s twice, use as" % (self.nid, comp))
            names.add(comp)
            self.fields.append((variables[f["var"]], comp))
        head = [v.name for v, _ in self.fields[:3]]
        if head != ["NID_MESSAGE", "L_MESSAGE", "T_TRAIN"]:
            fail("message %d: the header is NID_MESSAGE, L_MESSAGE, T_TRAIN"
                 % self.nid)
        self.rules = []
        optional_seen = False
        for r in rules:
            for key in r:
                if key not in ("nid", "one_of", "optional", "repeat", "from"):
                    fail("message %d: packet rule key %s" % (self.nid, key))
            if ("nid" in r) == ("one_of" in r):
                fail("message %d: a packet rule has nid or one_of"
                     % self.nid)
            nids = [int(r["nid"])] if "nid" in r else [int(x) for x in
                                                     r["one_of"]]
            if not 1 <= len(nids) <= 2:
                fail("message %d: one_of of %d packets" % (self.nid,
                                                           len(nids)))
            optional = bool(r.get("optional", False))
            if optional:
                optional_seen = True
            elif optional_seen:
                fail("message %d: a mandatory packet after optional ones"
                     % self.nid)
            senders = [str(x).lower() for x in r.get("from", SENDER_ORDER)]
            for x in senders:
                if x not in SENDERS:
                    fail("message %d: from %s" % (self.nid, x))
            for n in nids:
                if not 0 <= n <= 255:
                    fail("message %d: packet %d" % (self.nid, n))
            self.rules.append((nids, optional, bool(r.get("repeat", False)),
                               senders))


