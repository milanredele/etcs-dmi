class Level:
    """A record level: the packet, or the item of a loop."""

    def __init__(self, parent, access, depth):
        self.parent = parent
        self.access = access      # Ada prefix of its components: P or En
        self.depth = depth        # 0 for the packet
        self.names = set()
        self.reads = []           # (variable name, component, node) read
        self.components = []      # (component, type, default, comment)

    def unique(self, name):
        base = name
        n = 2
        while name in self.names or name.lower() in ADA_RESERVED:
            name = "%s_%d" % (base, n)
            n += 1
        self.names.add(name)
        return name


class VarNode:
    kind = "var"

    def __init__(self, var, comp, level):
        self.var = var
        self.comp = comp
        self.level = level
        self.count_of = None      # the LoopNode it counts
        self.raw_length_of = None  # the RawNode whose length it is


class IfNode:
    kind = "if"

    def __init__(self, text, level):
        self.text = text
        self.level = level
        self.children = []
        self.flag = None
        self.cond = None          # Ada expression, given the accesses
        self.cond_id = None


class LoopNode:
    kind = "loop"

    def __init__(self, count, level):
        self.count = count        # the VarNode of the count
        self.level = level
        self.children = []
        self.item = None          # Level of the item (None: single)
        self.list = None          # component name of the array
        self.item_type = None
        self.array_type = None
        self.single = False
        self.max = 0
        self.loop_id = None

    @property
    def depth(self):
        return self.level.depth + 1


class RawNode:
    kind = "raw"

    def __init__(self, level):
        self.level = level
        self.rest = False         # the rest of the packet (L_PACKET)
        self.length = None        # VarNode giving the length otherwise
        self.bits_comp = None
        self.data_comp = None
        self.max_bits = 0
        self.bits_type = None


def access(level, comp):
    return "%s.%s" % (level.access, comp)


def render_cond(ast, acc):
    """The Ada expression of a condition, components through acc."""
    ors = []
    for ands in ast:
        parts = []
        for lvl, node, op, vals in ands:
            ref = acc(lvl, node.comp)
            if op == "in":
                parts.append("%s in %s" % (ref, " | ".join(vals)))
            else:
                parts.append("%s %s %s" % (ref, op, vals[0]))
        ors.append(parts[0] if len(parts) == 1 else
                   "(" + " and then ".join(parts) + ")")
    return ors[0] if len(ors) == 1 else " or else ".join(ors)


def cond_refs(ast):
    return [(lvl, node) for ands in ast for lvl, node, _, _ in ands]


class Packet:
    def __init__(self, spec, variables, index):
        self.index = index
        try:
            self.nid = int(spec["nid"])
            self.name = str(spec["name"])
            self.clause = str(spec["clause"])
            self.direction = str(spec["direction"])
            fields = spec["fields"]
        except KeyError as e:
            fail("packet #%d: missing %s" % (index, e))
        if self.direction not in DIRECTIONS:
            fail("packet %d: direction %s" % (self.nid, self.direction))
        if not 0 <= self.nid <= 255:
            fail("packet %d: NID_PACKET not in 0 .. 255" % self.nid)
        self.sent_by = [str(s).lower() for s in spec.get("sent_by", [])]
        for s in self.sent_by:
            if s not in SENDERS:
                fail("packet %d: sent_by %s" % (self.nid, s))
        for key in spec:
            if key not in ("nid", "name", "clause", "direction", "sent_by",
                           "fields"):
                fail("packet %d: unknown key %s" % (self.nid, key))
        self.variables = variables
        self.dir_ada, self.parent_pkg, self.kind_prefix, self.dir_text, \
            _ = DIRECTIONS[self.direction]
        self.package = "%s.P%d" % (self.parent_pkg, self.nid)
        self.kind = "%s_P%d" % (self.kind_prefix, self.nid)
        self.file_base = "%s-p%d" % (self.parent_pkg.lower(), self.nid)
        self.type_names = set(["Packet_T"])
        self.item_types = []      # (LoopNode) in declaration order
        self.raw_types = []
        self.conditions = []      # IfNodes
        self.loops = []           # LoopNodes
        self.top = Level(None, "P", 0)
        self.nodes = self.resolve(fields, self.top)
        self.check_header()

    # -- names -------------------------------------------------------

    def type_name(self, base):
        name = base
        n = 2
        while name in self.type_names:
            name = "%s_%d" % (base, n)
            n += 1
        self.type_names.add(name)
        return name

    def lookup(self, name, level):
        """The component read last under this name at this level or an
        enclosing one: (VarNode, Level)."""
        lvl = level
        while lvl is not None:
            for var, comp, node in reversed(lvl.reads):
                if comp == name or var == name:
                    return node, lvl
            lvl = lvl.parent
        fail("packet %d: %s is not read before it is used"
             % (self.nid, name))

    @staticmethod
    def first_name(fields):
        for f in fields:
            if "var" in f:
                return f.get("as", f["var"])
            if "if" in f:
                n = Packet.first_name(f.get("fields", []))
                if n:
                    return n
            if "loop" in f:
                n = Packet.first_name(f.get("fields", []))
                if n:
                    return n + "_List"
            if "raw" in f:
                return "Raw"
        return None

    # -- conditions --------------------------------------------------

    def condition(self, text, level):
        """COND of SCHEMA.md, and/or of them: a list (or) of lists (and)
        of atoms (Level, VarNode, Ada operator or "in", values)."""
        def atom(a):
            a = a.strip()
            m = re.fullmatch(r"([A-Z][A-Z0-9_]*)\s+in\s+\[([^\]]*)\]", a)
            if m:
                node, lvl = self.lookup(m.group(1), level)
                vals = [self.value(node, v, "==")
                        for v in m.group(2).split(",")]
                return (lvl, node, "in", vals)
            m = re.fullmatch(r"([A-Z][A-Z0-9_]*)\s*(==|!=|<=|>=|<|>)\s*"
                             r"(-?\d+)", a)
            if not m:
                fail("packet %d: condition %r not understood"
                     % (self.nid, text))
            node, lvl = self.lookup(m.group(1), level)
            op = {"==": "=", "!=": "/=", "<": "<", "<=": "<=", ">": ">",
                  ">=": ">="}[m.group(2)]
            return (lvl, node, op, [self.value(node, m.group(3),
                                               m.group(2))])
        return [[atom(a) for a in re.split(r"\s+and\s+", part)]
                for part in re.split(r"\s+or\s+", text.strip())]

    def value(self, node, text, op):
        v = int(text.strip())
        var = node.var
        if not var.type_lo <= v <= var.type_hi:
            fail("packet %d: %s compared with %d, outside its %d bits"
                 % (self.nid, var.name, v, var.bits))
        # values the random test prefers, so that both outcomes occur
        for x in ((v,) if op == "==" else (v - 1, v, v + 1)):
            if var.is_valid(x):
                var.interesting.add(x)
        return str(v)

    # -- the tree ----------------------------------------------------

    def resolve(self, fields, level):
        nodes = []
        for f in fields:
            keys = [k for k in ("var", "if", "loop", "raw") if k in f]
            if len(keys) != 1:
                fail("packet %d: field %r: exactly one of var, if, loop,"
                     " raw" % (self.nid, f))
            k = keys[0]
            if k == "var":
                name = f["var"]
                if name not in self.variables:
                    fail("packet %d: variable %s is not described"
                         % (self.nid, name))
                for key in f:
                    if key not in ("var", "as"):
                        fail("packet %d: %s: unknown key %s"
                             % (self.nid, name, key))
                var = self.variables[name]
                comp = level.unique(f.get("as", name))
                node = VarNode(var, comp, level)
                level.reads.append((name, comp, node))
                level.components.append(
                    (comp, var.type_name, "0" if name != "NID_PACKET" or
                     level.parent else "NID", None))
                nodes.append(node)
            elif k == "if":
                node = IfNode(f["if"], level)
                node.cond_ast = self.condition(f["if"], level)
                first = self.first_name(f.get("fields", []))
                if first is None:
                    fail("packet %d: empty if %s" % (self.nid, f["if"]))
                node.flag = level.unique("Has_" + first)
                level.components.append(
                    (node.flag, "Boolean", "False",
                     "present when " + f["if"]))
                # what an if block reads is visible only inside it
                mark = len(level.reads)
                node.children = self.resolve(f["fields"], level)
                del level.reads[mark:]
                node.cond_id = len(self.conditions)
                self.conditions.append(node)
                nodes.append(node)
            elif k == "loop":
                count, clvl = self.lookup(f["loop"], level)
                var = count.var
                if var.signed or var.max < 1:
                    fail("packet %d: loop over %s" % (self.nid, var.name))
                node = LoopNode(count, level)
                node.count_level = clvl
                count.count_of = node
                node.max = var.max
                sub = f.get("fields", [])
                if not sub:
                    fail("packet %d: empty loop" % self.nid)
                first = self.first_name(sub)
                node.list = level.unique(first + "_List")
                base = first
                if len(sub) == 1 and "var" in sub[0]:
                    node.single = True
                    v = sub[0]["var"]
                    if v not in self.variables:
                        fail("packet %d: variable %s is not described"
                             % (self.nid, v))
                    node.elem_var = self.variables[v]
                    node.array_type = self.type_name(base + "_Array")
                    item = Level(level, None, level.depth + 1)
                    item.single_node = node
                    vnode = VarNode(node.elem_var, None, item)
                    node.children = [vnode]
                    level.components.append(
                        (node.list, node.array_type, "(others => 0)",
                         "loop over " + f["loop"]))
                else:
                    item = Level(level, "E%d" % (level.depth + 1),
                                 level.depth + 1)
                    node.item = item
                    node.item_type = self.type_name(base + "_Item")
                    node.array_type = self.type_name(base + "_Array")
                    node.children = self.resolve(sub, item)
                    level.components.append(
                        (node.list, node.array_type, None,
                         "loop over " + f["loop"]))
                    self.item_types.append(node)
                node.loop_id = len(self.loops)
                self.loops.append(node)
                nodes.append(node)
            else:
                node = RawNode(level)
                name = f["raw"]
                if name == "L_PACKET":
                    node.rest = True
                    node.max_bits = self.variables["L_PACKET"].max
                else:
                    lnode, llvl = self.lookup(name, level)
                    node.length = lnode
                    node.length_level = llvl
                    lnode.raw_length_of = node
                    node.max_bits = lnode.var.max
                node.max_bits = min(node.max_bits, 8 * 1024)
                node.bits_comp = level.unique("Raw_Bits")
                node.data_comp = level.unique("Raw")
                node.bits_type = self.type_name("Raw_Bits_T")
                node.data_type = self.type_name("Raw_Data_T")
                node.max_bytes = (node.max_bits + 7) // 8
                self.raw_types.append(node)
                level.components.append(
                    (node.bits_comp, node.bits_type, "0",
                     "bits of " + ("the rest of the packet" if node.rest
                                   else name)))
                level.components.append(
                    (node.data_comp, node.data_type, "(others => 0)",
                     "the bits, from the first byte on"))
                nodes.append(node)
        return nodes

    def check_header(self):
        names = [n.var.name for n in self.nodes if n.kind == "var"]
        if not names or names[0] != "NID_PACKET":
            fail("packet %d: the first field must be NID_PACKET" % self.nid)
        expect = ["NID_PACKET"]
        if self.direction == "track_to_train":
            expect.append("Q_DIR")
        expect.append("L_PACKET")
        head = [n.var.name if n.kind == "var" else None
                for n in self.nodes[:len(expect)]]
        self.has_length = head == expect
        if not self.has_length:
            if any(n.kind == "var" and n.var.name == "L_PACKET"
                   for n in self.nodes):
                fail("packet %d: the header must be %s"
                     % (self.nid, ", ".join(expect)))
            if any(n.kind == "raw" and n.rest for n in self.all_nodes()):
                fail("packet %d: raw L_PACKET without L_PACKET" % self.nid)
        for n in self.all_nodes():
            if n.kind == "raw" and n.rest:
                if n.level is not self.top or self.nodes[-1] is not n:
                    fail("packet %d: raw = L_PACKET must be the last field"
                         % self.nid)

    def all_nodes(self, nodes=None):
        for n in (self.nodes if nodes is None else nodes):
            yield n
            if n.kind in ("if", "loop"):
                yield from self.all_nodes(n.children)

    # -- sizes -------------------------------------------------------

    def record_size(self):
        def level_size(nodes):
            size = 0
            for n in nodes:
                if n.kind == "var":
                    size += n.var.size_bytes()
                elif n.kind == "if":
                    size += 1 + level_size(n.children)
                elif n.kind == "loop":
                    if n.single:
                        size += n.max * n.elem_var.size_bytes()
                    else:
                        size += n.max * level_size(n.children)
                else:
                    size += 4 + n.max_bytes
            return size
        return level_size(self.nodes)



