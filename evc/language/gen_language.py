def fn_decl(indent, head_parts, expr_lines, aspects):
    """An expression function, on one line when it fits."""
    pad = " " * indent
    one = pad + " ".join(head_parts) + " is"
    out = []
    if len(one) <= MAX_LINE and len(pad + "  " + expr_lines) <= MAX_LINE:
        out.append(one)
        out.append(pad + "  " + expr_lines)
    else:
        out.append(pad + head_parts[0] + " " + head_parts[1])
        out.append(pad + "  " + " ".join(head_parts[2:]))
        out.append(pad + "is " + expr_lines)
    if aspects:
        out[-1] += ""
        out.append(pad + "  with " + aspects + ";")
    else:
        out[-1] += ";"
    return out


