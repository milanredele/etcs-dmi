def header(what):
    """The first lines of every generated Ada file."""
    lines = ["--  ETCS on-board (EVC)"] + wrap_comment(what, 0) + [
        "--",
        "--  GENERATED by " + GENERATOR + " from",
        "--  " + SOURCE + ". Do not edit: change the TOML and run",
        "--  python3 " + GENERATOR + " (--check verifies).",
    ]
    return lines


def wrap_comment(text, indent, first_prefix="--  "):
    """A comment of several lines, words kept whole."""
    pad = " " * indent
    width = MAX_LINE - indent - len(first_prefix)
    words = text.split()
    lines = []
    cur = ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > width:
            lines.append(pad + first_prefix + cur)
            cur = w
        else:
            cur = (cur + " " + w) if cur else w
    if cur:
        lines.append(pad + first_prefix + cur)
    return lines


def ada_string(text):
    return '"' + text.replace('"', '""') + '"'


def identifier(text):
    """Words of text as an Ada identifier (Capitalised_Words)."""
    words = re.findall(r"[A-Za-z0-9]+", text)
    out = []
    for w in words:
        if w.isupper() and len(w) > 1:
            out.append(w)
        else:
            out.append(w[0].upper() + w[1:].lower())
    return "_".join(out)


def check_line_lengths(name, text):
    for n, line in enumerate(text.split("\n"), 1):
        if len(line) > MAX_LINE:
            fail("%s:%d: generated line longer than %d characters:\n%s"
                 % (name, n, MAX_LINE, line))


