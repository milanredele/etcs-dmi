def stmt(lines, indent, text):
    """A statement, wrapped after ":=" when too long."""
    pad = " " * indent
    if len(pad + text) <= MAX_LINE:
        lines.append(pad + text)
        return
    m = re.match(r'(.*?)("(?:[^"]|"")*")(;?)$', text)
    if m and len(pad + m.group(1)) < MAX_LINE - 20:
        # a long string literal: pieces joined with &
        head, lit, end = m.group(1), m.group(2)[1:-1], m.group(3)
        width = MAX_LINE - len(pad) - 8
        pieces = []
        while lit:
            cut = min(len(lit), width)
            if cut < len(lit):
                sp = lit.rfind(" ", 0, cut)
                if sp > 10:
                    cut = sp
            piece = lit[:cut]
            if piece.endswith('"') and piece.count('"') % 2:
                piece = piece[:-1]
                cut -= 1
            pieces.append(piece)
            lit = lit[cut:]
        lines.append(pad + head.rstrip())
        for i, piece in enumerate(pieces):
            lines.append(pad + "  " + ("& " if i else "") + '"' + piece
                         + '"' + (end if i == len(pieces) - 1 else ""))
        return
    m = re.match(r"(.*?) renames (.*)$", text)
    if m:
        lines.append(pad + m.group(1))
        lines.append(pad + "  renames " + m.group(2))
        return
    m = re.match(r"(.*?) := (.*)$", text)
    if m:
        lines.append(pad + m.group(1) + " :=")
        lines.append(pad + "  " + m.group(2))
        return
    m = re.match(r"(\w+) \((.*)\);$", text)
    if m:
        args = m.group(2).split(", ")
        lines.append(pad + m.group(1))
        lines.append(pad + "  (" + args[0] + ",")
        for a in args[1:-1]:
            lines.append(pad + "   " + a + ",")
        lines.append(pad + "   " + args[-1] + ");")
        return
    lines.append(pad + text)


def cond_lines(lines, indent, keyword, cond, after):
    """if/elsif COND then, wrapped on "and then"/"or else"."""
    pad = " " * indent
    one = "%s%s %s %s" % (pad, keyword, cond, after)
    if len(one) <= MAX_LINE:
        lines.append(one)
        return
    parts = re.split(r" (and then|or else) ", cond)
    lines.append("%s%s %s" % (pad, keyword, parts[0]))
    i = 1
    while i < len(parts):
        lines.append("%s  %s %s" % (pad, parts[i], parts[i + 1]))
        i += 2
    lines.append(pad + after)


def spec_components(lines, comps, indent):
    width = max(len(c[0]) for c in comps)
    pad = " " * indent
    for comp, typ, default, comment in comps:
        if comment:
            lines += wrap_comment(comment, indent)
        text = "%s%s : %s" % (pad, comp.ljust(width), typ)
        if default is not None:
            text += " := %s" % default
        text += ";"
        if len(text) > MAX_LINE:
            lines.append("%s%s :" % (pad, comp))
            t2 = "%s  %s" % (pad, typ)
            if default is not None:
                t2 += " := %s" % default
            lines.append(t2 + ";")
        else:
            lines.append(text)


