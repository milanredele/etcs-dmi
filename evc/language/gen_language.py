def valid_tree(p, nodes):
    """The conjuncts of the validity of a record level, as terms:
    ("atom", text), ("if", flag, [terms]), ("all", index, count, term),
    ("guard", text, term)."""
    terms = []
    for n in nodes:
        if n.kind == "var":
            terms.append(("atom", "Is_Valid (%s)"
                          % access(n.level, n.comp)))
        elif n.kind == "if":
            sub = valid_tree(p, n.children)
            if sub:
                terms.append(("if", access(n.level, n.flag), sub))
        elif n.kind == "loop":
            if n.count_level is not n.level:
                fail("packet %d: the count of %s is read at an enclosing"
                     " level: Valid does not support it" % (p.nid, n.list))
            idx = "I%d" % n.depth
            count = "Natural (%s)" % access(n.level, n.count.comp)
            element = "%s (%s)" % (access(n.level, n.list), idx)
            if n.single:
                body = ("atom", "Is_Valid (%s)" % element)
            else:
                body = ("atom", "Valid_%s (%s)" % (n.item_type, element))
            term = ("all", idx, count, body)
            if needs_guard(n):
                term = ("guard", "%s <= %d" % (count, n.max), term)
            terms.append(term)
    return terms


def one_line(t):
    if t[0] == "atom":
        return t[1]
    if t[0] == "if":
        return "(if %s then %s)" % (t[1], " and then ".join(
            one_line(x) for x in t[2]))
    if t[0] == "all":
        return "(for all %s in 1 .. %s => %s)" % (t[1], t[2], one_line(t[3]))
    return "(%s and then %s)" % (t[1], one_line(t[2]))


def lay_conj(terms, col):
    """Lines of a conjunction starting at column col: the first without
    its indentation, the others whole."""
    lines = lay(terms[0], col)
    for t in terms[1:]:
        sub = lay(t, col + 9)
        lines.append(" " * col + "and then " + sub[0])
        lines += sub[1:]
    return lines


def lay(t, col):
    text = one_line(t)
    if col + len(text) + 3 <= MAX_LINE:
        return [text]
    if t[0] == "atom":
        # a call: its arguments on the next line
        m = re.match(r"(\w+) (\(.*\))$", text)
        if m:
            return [m.group(1), " " * (col + 2) + m.group(2)]
        return [text]
    if t[0] == "if":
        body = lay_conj(t[2], col + 6)
        lines = ["(if " + t[1], " " * (col + 1) + "then " + body[0]]
        lines += body[1:]
    elif t[0] == "all":
        body = lay(t[3], col + 3)
        lines = ["(for all %s in 1 .. %s =>" % (t[1], t[2]),
                 " " * (col + 3) + body[0]]
        lines += body[1:]
    else:
        body = lay_conj([("atom", t[1]), t[2]], col + 1)
        lines = ["(" + body[0]] + body[1:]
    lines[-1] += ")"
    return lines


def valid_function(name, formal, terms):
    head = "   function %s (%s) return Boolean is" % (name, formal)
    if len(head) <= MAX_LINE:
        lines, pad = [head], "     ("
    else:
        lines = ["   function %s" % name,
                 "     (%s) return Boolean" % formal]
        pad = "   is ("
    body = lay_conj(terms, len(pad)) if terms else ["True"]
    body[-1] += ");"
    return lines + [pad + body[0]] + body[1:]


def gen_valid(p):
    L = []
    for n in sorted(p.item_types, key=lambda n: -n.depth):
        L.append("   --  Valid of one item of %s" % n.list)
        L += valid_function("Valid_" + n.item_type, "%s : %s"
                            % (n.item.access, n.item_type),
                            valid_tree(p, n.children))
        L.append("")
    L += ["   -----------", "   -- Valid --", "   -----------", ""]
    L += valid_function("Valid", "P : Packet_T", valid_tree(p, p.nodes))
    L.append("")
    return L


def gen_packet_body(p):
    L = header("Packet %d, %s: %s, implementation." % (
        p.nid, p.dir_text, p.name))
    L += ["", "with Interfaces; use Interfaces;", "",
          "package body %s" % p.package, "  with SPARK_Mode => On",
          "is", ""]
    empties = [n for n in sorted(p.item_types, key=lambda n: -n.depth)
               if not always_assigned(n.children)]
    if empties:
        L.append("   --  The items with every component at its default")
        for n in empties:
            stmt(L, 3, "Empty_%s : constant %s := (others => <>);"
                 % (n.item_type, n.item_type))
        L.append("")
    L += gen_item_procedures(p, "decode")
    L += gen_item_procedures(p, "encode")
    L += gen_valid(p)
    # Decode: into local variables, the record assigned once at the end
    # (one aggregate instead of a chain of updates of a large record:
    # small proof tasks)
    dec = Emitter(p, "decode", locals_=True)
    body = []
    dec.emit(p.nodes, body, 6)
    direct = set(n.comp if n.kind == "var" else n.flag
                 for n in p.nodes if n.kind in ("var", "if"))
    uses_bad = needs_flag(p.nodes, "decode")
    L += [
        "   ------------",
        "   -- Decode --",
        "   ------------",
        "",
        "   procedure Decode (R  : in out Reader;",
        "                     P  : out Packet_T;",
        "                     OK : out Boolean)",
        "   is",
    ]
    if p.has_length:
        L.append("      Start : constant Natural := Position (R);")
    L.append("      V     : Unsigned_64;")
    if uses_bad:
        L.append("      Bad   : Boolean := False;")
    comps = p.top.components
    width = max(len(c[0]) for c in comps)
    for comp, typ, default, _ in comps:
        text = "      %s : %s" % (comp.ljust(width), typ)
        if comp not in direct and default is not None:
            text += " := %s" % default
        stmt(L, 0, text + ";")
    L.append("   begin")
    L += body
    L.append("      P :=")
    for i, (comp, _, _, _) in enumerate(comps):
        L.append("        %s%s => %s%s" % (
            "(" if i == 0 else " ", comp, comp,
            "," if i < len(comps) - 1 else ");"))
    ok = ["not Failed (R)"]
    if uses_bad:
        ok.append("not Bad")
    ok.append("NID_PACKET = NID")
    if p.has_length:
        ok.append("Position (R) = Start + Natural (L_PACKET)")
    L.append("      OK := " + ok[0])
    for o in ok[1:]:
        L.append("        and then " + o)
    L[-1] += ";"
    L += ["   end Decode;", ""]
    # Encode
    enc = Emitter(p, "encode")
    body = []
    enc.emit(p.nodes, body, 6)
    uses_good = needs_flag(p.nodes, "encode") or p.has_length
    L += [
        "   ------------",
        "   -- Encode --",
        "   ------------",
        "",
        "   procedure Encode (P  : Packet_T;",
        "                     W  : in out Writer;",
        "                     OK : out Boolean)",
        "   is",
    ]
    if p.has_length:
        L.append("      Start     : constant Natural := Position (W);")
        L.append("      Length_At : Natural;")
    if uses_good:
        L.append("      Good      : Boolean := True;")
    if not any("P." in b for b in body):
        L.append("      pragma Unreferenced (P);")
    L.append("   begin")
    L += body
    if p.has_length:
        lmax = p.variables["L_PACKET"].max
        lbits = p.variables["L_PACKET"].bits
        L += [
            "      --  L_PACKET: the bits written",
            "      if Position (W) >= Start",
            "        and then Position (W) - Start <= %d" % lmax,
            "      then",
            "         Patch (W, Length_At, %d, Unsigned_64 (Position (W)"
            " - Start));" % lbits,
            "      else",
            "         Good := False;",
            "      end if;",
        ]
    if uses_good:
        L.append("      OK := Good and then not Failed (W);")
    else:
        L.append("      OK := not Failed (W);")
    L += ["   end Encode;", "", "end %s;" % p.package, ""]
    return "\n".join(L)


