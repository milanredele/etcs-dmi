#!/usr/bin/env python3
"""Generate the Ada codec of the ERTMS/ETCS language from its description.

Reads evc/language/etcs_language.toml (format: evc/language/SCHEMA.md)
and writes:

  evc/language/etcs_variables.ads        the variables of 7.5 (Pure, SPARK)
  evc/language/etcs_catalogue.ads/.adb   NID_PACKET -> kind, direction,
                                         clause, senders; decode check
                                         and skip by L_PACKET
  evc/language/etcs_track_packets.ads    parent of the track to train
                                         packets (7.4.2)
  evc/language/etcs_track_packets-p<N>.ads/.adb   one per packet:
                                         record, Decode, Encode (SPARK)
  evc/language/etcs_train_packets*.ad?   the same, train to track (7.4.3)
  test/src/etcs_language_random.ads/.adb random valid packets and round
                                         trips for evc_test (host only)

Usage:
  python3 evc/language/gen_language.py            regenerate
  python3 evc/language/gen_language.py --check    fail if the checked in
                                                  files differ
  python3 evc/language/gen_language.py --stats    sizes, for the memory

Python 3.11 or later (tomllib), standard library only. The output is
deterministic: the same TOML gives the same bytes.
"""

