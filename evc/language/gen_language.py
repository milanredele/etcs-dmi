def wrap_list(text, indent):
    """A comma separated text over lines of the maximum length."""
    pad = " " * indent
    out = []
    cur = ""
    for piece in text.split(", "):
        add = (cur + ", " + piece) if cur else piece
        if cur and len(pad + add) + 1 > MAX_LINE:
            out.append(pad + cur + ",")
            cur = piece
        else:
            cur = add
    out.append(pad + cur)
    return out


