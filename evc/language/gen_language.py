def generate(variables, packets, messages):
    """{path relative to the repository: text}"""
    out = {}
    conds, loops = [], []
    for p in packets:
        for n in p.conditions:
            n.fill_id = len(conds)
            conds.append((p, n))
        for n in p.loops:
            n.fill_id = len(loops)
            loops.append((p, n))
    out["evc/language/etcs_variables.ads"] = gen_variables(variables)
    out["evc/language/etcs_catalogue.ads"] = gen_catalogue_spec(variables,
                                                                packets)
    out["evc/language/etcs_catalogue.adb"] = gen_catalogue_body(variables,
                                                                packets)
    for d in DIRECTION_ORDER:
        pkg = DIRECTIONS[d][1]
        out["evc/language/%s.ads" % pkg.lower()] = gen_parent(
            d, [p for p in packets if p.direction == d])
    for p in packets:
        out["evc/language/%s.ads" % p.file_base] = gen_packet_spec(p)
        out["evc/language/%s.adb" % p.file_base] = gen_packet_body(p)
    out["evc/language/etcs_message_catalogue.ads"] = gen_messages_spec(
        variables, messages)
    out["evc/language/etcs_message_catalogue.adb"] = gen_messages_body(
        messages)
    out["test/src/etcs_language_random.ads"] = gen_random_spec(
        packets, conds, loops)
    out["test/src/etcs_language_random.adb"] = gen_random_body(
        variables, packets, conds, loops)
    for name, text in out.items():
        check_line_lengths(name, text)
    return out


def generated_pattern(rel):
    """Paths the generator owns (stale ones are removed)."""
    base = os.path.basename(rel)
    return (rel.startswith("evc/language/")
            and (base == "etcs_variables.ads"
                 or base.startswith("etcs_catalogue.")
                 or base.startswith("etcs_message_catalogue.")
                 or base.startswith("etcs_track_packets")
                 or base.startswith("etcs_train_packets"))) \
        or rel in ("test/src/etcs_language_random.ads",
                   "test/src/etcs_language_random.adb")


def existing_generated():
    found = set()
    for d, prefix in ((LANG_DIR, "evc/language/"),
                      (TEST_DIR, "test/src/")):
        for f in os.listdir(d):
            rel = prefix + f
            if generated_pattern(rel):
                found.add(rel)
    return found


def stats(variables, packets, messages):
    print("variables: %d" % len(variables))
    for d in DIRECTION_ORDER:
        ms = [m for m in messages if m.direction == d]
        print("messages %s: %d" % (DIRECTIONS[d][3], len(ms)))
    for d in DIRECTION_ORDER:
        ps = [p for p in packets if p.direction == d]
        print("packets %s: %d" % (DIRECTIONS[d][3], len(ps)))
    print()
    print("%-10s %-50s %8s" % ("kind", "name", "bytes"))
    total = 0
    biggest = None
    for p in packets:
        size = p.record_size()
        total += size
        if biggest is None or size > biggest[0]:
            biggest = (size, p)
        print("%-10s %-50s %8d" % (p.kind, p.name[:50], size))
    print()
    print("record sizes (estimate, no padding): total %d bytes, largest %d"
          " (%s)" % (total, biggest[0], biggest[1].kind))
    print("decoding one packet on demand needs the largest record on the"
          " stack")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="fail if the checked in files differ")
    ap.add_argument("--stats", action="store_true",
                    help="print the sizes of the packet records")
    ap.add_argument("--toml", default=TOML_PATH)
    args = ap.parse_args()
    try:
        variables, packets, messages = load(args.toml)
        out = generate(variables, packets, messages)
    except GenError as e:
        print("gen_language.py: " + str(e), file=sys.stderr)
        return 1
    if args.stats:
        stats(variables, packets, messages)
        return 0
    if args.check:
        # regenerate into a temporary directory and compare
        bad = 0
        with tempfile.TemporaryDirectory() as tmp:
            for rel, text in sorted(out.items()):
                path = os.path.join(tmp, rel)
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
            for rel in sorted(out):
                mine = os.path.join(REPO, rel)
                with open(os.path.join(tmp, rel), encoding="utf-8") as f:
                    fresh = f.read()
                if not os.path.exists(mine):
                    print("missing: " + rel)
                    bad += 1
                    continue
                with open(mine, encoding="utf-8") as f:
                    old = f.read()
                if old != fresh:
                    print("differs: " + rel)
                    for line in list(difflib.unified_diff(
                            old.split("\n"), fresh.split("\n"),
                            rel, "generated", lineterm=""))[:20]:
                        print("  " + line)
                    bad += 1
            for rel in sorted(existing_generated() - set(out)):
                print("stale: " + rel)
                bad += 1
        if bad:
            print("gen_language.py --check: %d file(s) differ; run"
                  " python3 %s" % (bad, GENERATOR))
            return 1
        print("gen_language.py --check: %d files up to date" % len(out))
        return 0
    for rel in sorted(existing_generated() - set(out)):
        os.remove(os.path.join(REPO, rel))
        print("removed " + rel)
    changed = 0
    for rel, text in sorted(out.items()):
        path = os.path.join(REPO, rel)
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                old = f.read()
        if old != text:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            changed += 1
    print("gen_language.py: %d files, %d written" % (len(out), changed))
    return 0


if __name__ == "__main__":
    sys.exit(main())
